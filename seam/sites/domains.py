def _check() -> None:
    for name, d in LIB.items():
        missing = [k for k in REQUIRED if k not in d]
        assert not missing, f"{name}: domain library missing {missing}"
        assert len(d["nav"]) == 5 and len(d["icons"]) == 5, name
        assert len(d["steps"]) == 3 and len(d["buttons"]) == 3, name
        if d["media"] == "map":
            assert d.get("map_caption"), f"{name}: media=map needs map_caption"


_check()
