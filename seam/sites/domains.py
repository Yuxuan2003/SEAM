"""S8 domain library: the scaffolding around an authored construct.

An S8 rule (s8/rules.py) states only the construct -- the person fact, the
object fact, how they bind, what must be computed, and the label per arm. It
says nothing about branding, navigation, prices, summary rows or button text.
That is deliberate: the review of 2026-10-21 found that the frozen bank's
diversity came from *scenario dressing* while the reasoning repeated, so in S8
the two are separated and only the construct is authored by hand.

This module is the other half: per domain, one app with its own brand, colour,
navigation, stepper, media style and commercial furniture. 150 rules over 33
domains means the scaffolding varies with the domain and never with the rule,
so a rule cannot accidentally be made identifiable by its dressing.

Required keys are checked at import (see `_check`), because a missing key would
otherwise surface as a jinja StrictUndefined error inside a render of 1200
pages.

`{obj}` in any string is formatted with the rule's object name.
"""

